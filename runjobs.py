#!/usr/bin/env python3
"""Original SQD runjobs.py workflow, adapted to 2D fitted J1/J2 and 2-arm MFE.

Prepare scan folders and split thermal trajectories across serial.py Slurm jobs.
Every job runs ALL material cases and phases for a *different seed range*,
allowing paired comparison with common initial thermal random numbers.

Examples:
 python runjobs.py --input input_brownian.txt --output-root cluster_runs --jobs 5 --traj-per-job 20 --mode prepare
 python runjobs.py --input input_brownian.txt --output-root cluster_runs --jobs 5 --traj-per-job 20 --mode sbatch
 python runjobs.py --input input_brownian.txt --output-root scan_J --jobs 5 --traj-per-job 20 --scan brownian_amplitude_multiplier_2=1.0,1.4 --mode prepare

For local debugging use --mode local with small --jobs and --traj-per-job.
"""
import argparse
import ast
import itertools
from pathlib import Path
import re
import shutil
import subprocess
import sys

from Model.polaritonmod import parameters

FILES=('serial.py','runjobs.py','run.py','avg.py','initialMC.py','plot_results.py',
       'animate_interference.py','plot_localization.py','plot_brownian_fit.py')
DIRS=('Model','Method','spectra')


def parse_scan(value):
    if '=' not in value:
        raise ValueError(f'Expected --scan KEY=val1,val2, got {value!r}')
    key,values=value.split('=',1)
    key=key.strip().lstrip('$')
    if not re.fullmatch(r'[A-Za-z_]\w*',key):
        raise ValueError('Invalid parameter name: '+key)
    if key not in parameters.__dataclass_fields__ or not parameters.__dataclass_fields__[key].init:
        raise ValueError('Parameter is not an editable model input: '+key)
    parts=[x.strip() for x in values.split(',') if x.strip()]
    if not parts:raise ValueError('Scan must contain at least one value')
    out=[]
    for item in parts:
        try:out.append(ast.literal_eval(item))
        except (SyntaxError,ValueError):out.append(item)
    return key,out


def slug(value):
    s=str(value).replace('.','p').replace('-','m')
    return re.sub('[^A-Za-z0-9_]+','_',s)[:80]


def prepare(source_dir, source_input, target, overrides, jobs, count, reuse=False):
    if target.exists() and any(target.iterdir()):
        if not reuse:
            raise FileExistsError(f'{target}: exists. Choose a new output root or use --reuse for identical inputs')
    else:
        target.mkdir(parents=True,exist_ok=True)
        for file in FILES:
            shutil.copy2(source_dir/file,target/file)
        for directory in DIRS:
            if (source_dir/directory).exists():
                shutil.copytree(source_dir/directory,target/directory)
    # SQD input-file overrides appended just as in the original runjobs.py.
    lines=source_input.read_text()
    if not lines.endswith('\n'):lines+='\n'
    lines+='\n# Automatically generated by SQD-style 2D runjobs.py\n'
    for key,val in overrides.items():
        lines+=f'${key} = {val!r}\n'
    lines+=f'$NTraj = {jobs*count}\n'
    dest=target/'input.txt'
    if dest.exists():
        if dest.read_text()!=lines:
            raise ValueError(f'Existing {dest} is different; refuse to silently change prior job physics')
    else:
        dest.write_text(lines)
    (target/'logs').mkdir(exist_ok=True)
    return target


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--input',default='input_brownian.txt')
    ap.add_argument('--output-root',default='cluster_runs')
    ap.add_argument('--jobs',type=int,default=5)
    ap.add_argument('--traj-per-job',type=int,default=20)
    ap.add_argument('--scan',action='append',default=[],metavar='KEY=VAL1,VAL2',
                    help='Repeat flag for multiple scanned parameters (Cartesian product)')
    ap.add_argument('--mode',choices=['prepare','local','sbatch'],default='prepare')
    ap.add_argument('--reuse',action='store_true',help='Reuse identically prepared scans')
    a=ap.parse_args()
    if a.jobs<=0 or a.traj_per_job<=0:raise ValueError('jobs and traj-per-job must be positive')
    project=Path(__file__).resolve().parent
    inp=Path(a.input).resolve()
    if not inp.exists():raise FileNotFoundError(inp)
    output_root=Path(a.output_root).resolve()
    if output_root == project:
        raise ValueError('Output root should be a new subdirectory, not the project root')
    scan_defs=[parse_scan(s) for s in a.scan]
    names=[x for x,_ in scan_defs]
    if len(names)!=len(set(names)):raise ValueError('Duplicate scan key')
    products=itertools.product(*(x for _,x in scan_defs)) if scan_defs else [()]
    for vals in products:
        opts=dict(zip(names,vals))
        label='_'.join(f'{key}={slug(val)}' for key,val in opts.items()) or 'default'
        case_dir=prepare(project,inp,output_root/label,opts,a.jobs,a.traj_per_job,a.reuse)
        print('Prepared:',case_dir,flush=True)
        for jid in range(a.jobs):
            start=jid*a.traj_per_job
            cmd=['--input','input.txt','--output',f'job_{jid:03d}',
                 '--traj-start',str(start),'--traj-count',str(a.traj_per_job)]
            if a.mode=='prepare':
                print('  batch',jid,'seed indices',start,'to',start+a.traj_per_job-1)
            elif a.mode=='local':
                subprocess.run([sys.executable,'serial.py',*cmd],cwd=case_dir,check=True)
            else:
                subprocess.run(['sbatch',f'--chdir={case_dir}',
                                f'--output=logs/job_%j.out','serial.py',*cmd],
                               cwd=case_dir,check=True)
        if a.mode=='local':
            subprocess.run([sys.executable,'avg.py','--input','input.txt',
                            '--root','.','--output','results_ensemble'],cwd=case_dir,check=True)
            subprocess.run([sys.executable,'plot_results.py','--input','input.txt',
                            '--results','results_ensemble'],cwd=case_dir,check=True)
        else:
            print('  When all Slurm jobs finish, run:')
            print(f'  cd "{case_dir}" && python avg.py --input input.txt --output results_ensemble')
            print('  python plot_results.py --input input.txt --results results_ensemble')


if __name__=='__main__':
    main()
